-- 團隊裡目前開發資料庫的資料表，都是每個工程師自己手動在資料庫裡執行 SQL 建出來的，沒有留下任何紀錄檔案。有一天，正式環境要開一個新的測試環境，卻沒有人能一次講清楚目前的資料表結構總共長什麼樣子、之前改過哪些欄位。

-- 請根據以上情境，回答下列問題：

-- 這個團隊目前遇到的問題，跟今天學到的哪個概念直接相關？如果導入這個做法，能解決情境裡描述的哪些困擾？
migration。1.多人進行維護，會不知道資料表最新的狀態。 2.重新建置，可以依照migration的記錄。

這跟「Migration（資料表結構管理）」直接相關。團隊目前手動建表、沒有留下紀錄，導致沒人能完整說明目前的結構、也不知道歷史上改過什麼。如果導入 migration，把每一次建表、改欄位都寫成一份可保留的紀錄，之後不管是新人接手、還是要在新環境重建一樣的資料庫，都只要照著這些紀錄依序重跑一次即可，不用再靠口頭說明或東拼西湊。

-- 如果之後要幫某張資料表新增一個欄位，導入 migration 之後，正確的做法應該是「回去修改原本建立這張表的那份 migration」，還是「另外寫一份新的 migration 來新增欄位」？為什麼？
(xxx)回去修改原本建立這張表的那份 migration。共同維護，才有延續先前的過程，資料表才會完整的。

應該是「另外寫一份新的 migration 來新增欄位」，而不是回去修改原本建表的那份。因為 migration 的價值就在於「保留每一次變更的歷史紀錄」——如果直接回頭改舊的 migration，等於把當初的紀錄抹掉了，之後也沒辦法知道「這個欄位是什麼時候、為了什麼原因加上去的」，失去了 migration 原本要解決的問題。


-- 「開發階段的資料庫可以安全重置」跟今天學到的哪個特性有關？如果沒有這個做法，重置資料庫會有什麼風險或麻煩？
中途更改的過程沒有記錄到，資料表會有缺失。

這跟「結構可以被完整記錄、隨時重建」的特性有關。因為所有建表、修改欄位的動作都寫成了 migration，只要把資料庫清空、重新依序執行一次這些紀錄，就能回到一模一樣的乾淨結構。如果沒有這個做法，重置資料庫會很麻煩：得靠人工回想或翻找過去的操作紀錄，才能把資料表一個一個手動建回來，過程中很容易漏掉某些欄位或調整，導致重置後的結構跟原本的不一致。
