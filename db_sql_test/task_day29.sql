-- 健身房系統的 bookings 表目前有 10 萬筆預約紀錄，其中 status 欄位只有三種值：active（3 萬筆）、cancelled（3.5 萬筆）、completed（3.5 萬筆），分布相當平均；member_id 則對應約 500 位會員，平均每位會員只有 200 筆左右的預約紀錄。

-- 同事想加速這條查詢，卻不確定該怎麼建索引：

-- SELECT * FROM bookings WHERE member_id = 1 AND status = 'active';
-- 他先嘗試「只幫 status 建索引」，結果 EXPLAIN ANALYZE 顯示資料庫依然選擇 Seq Scan，索引完全沒被用到。

-- 根據以上情境，回答下列問題：

-- 為什麼「只幫 status 建索引」沒有效果？跟 status 的選擇性有什麼關係？
因為條件很常見，符合的資料很多。例如 status 如果只有 active / cancelled / completed 三種值，隨便一種狀態都可能佔了整體資料的三分之一。

status 只有三種值，每一種都佔了整體資料的三分之一左右，選擇性非常低——不管查哪個 status，都會篩出好幾萬筆資料。對選擇性這麼低的欄位建索引幾乎沒有幫助，資料庫評估後會認為直接整張表掃過去（Seq Scan）比查索引更快，索引就會被略過不用。

-- 如果改成「只幫 member_id 建索引」，這條查詢會變快嗎？還有沒有可以再優化的空間？
會變快，一個會員通常只對應少數幾筆預約。
可以使用複合索引再優化，因為多數時候是要找有效的指定會員。

會比原本快一些。member_id 平均每個值只對應 200 筆左右的資料，選擇性高很多，建索引後可以先快速定位到這個會員的所有預約。但接下來還是要把這 200 筆資料一筆一筆用 Filter 篩掉 status 不是 active 的部分，還有多一層篩選的成本，不是最理想的做法。

-- 如果要建立一個複合索引來加速這條查詢，應該把 member_id 還是 status 放在前面？為什麼？
member_id 放在前面。因為選擇性高，件很稀有，符合的資料很少，所以可以一次篩選掉最多的資料。
