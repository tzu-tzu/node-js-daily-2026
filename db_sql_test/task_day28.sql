-- 健身房系統的 bookings 表已經累積 10 萬筆預約紀錄。同事最近常查「某會員的預約紀錄」，覺得速度變慢，於是幫 member_id 建了索引，並回報建立索引前後的變化：

-- 建索引前：查詢用 Seq Scan，整張表 10 萬筆逐筆比對，Execution Time 約 20 ms
-- 建索引後：查詢改用 Index Scan，Execution Time 降到約 0.2 ms
-- 根據以上情境，回答下列問題：

-- 為什麼建立索引後，查詢方式會從 Seq Scan 變成 Index Scan？這跟資料庫內部多了什麼東西有關？
會先依照索引排序，新增一張表，可以透過排序好的表更快找到資料

建立索引之後，資料庫會另外生成一份依 member_id 排好序的副本，並記著每筆資料在原表的位置。查詢時可以像查字典一樣，直接對半縮小範圍去定位，不用像沒排序的書一樣從頭翻到尾，所以會改用 Index Scan。

-- 如果 bookings 表只有 100 筆資料，你覺得建不建索引，查詢速度感覺得出差異嗎？為什麼？
沒有，因為筆數太少

感覺不太出來。因為資料量只有 100 筆，就算逐筆掃過（Seq Scan）也很快，索引帶來的「對半縮小範圍」優勢在小資料量下不明顯，只有資料量夠大（例如 10 萬筆以上）時，兩者的時間差距才會明顯拉開。

-- 如果同事接著說「乾脆把 bookings 表每個欄位都建索引，以後查詢都會變快」，你會怎麼回應？
不可以，建立索引是會有額外的空間使用，亦會影響到存入的速度，需要評估。

索引不是免費的：每個索引都要佔用額外的儲存空間，而且每次新增、修改、刪除資料時，資料庫都要同步更新索引，索引越多寫入就越慢。所以應該只針對真正常被拿來查詢的欄位建索引，而不是每個欄位都建。
